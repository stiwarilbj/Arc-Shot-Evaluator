import assert from 'node:assert/strict';
import { build } from '../frontend/node_modules/vite/dist/node/index.js';
import { installBrowserLocks } from './helpers/browser-locks.mjs';
const locks = installBrowserLocks();
const output = await build({ configFile: false, logLevel: 'silent', define: { 'import.meta.env.VITE_DEPLOY_TARGET': JSON.stringify('github-pages') }, build: { write: false, lib: { entry: new URL('../frontend/src/features/playbook/api.ts', import.meta.url).pathname, formats: ['es'], fileName: 'api' }, minify: false } });
const code = (Array.isArray(output) ? output[0] : output).output[0].code;
// Independent module instances have separate queues and caches, like tabs.
const clients = await Promise.all([1, 2, 3].map(id => import(`data:text/javascript;base64,${Buffer.from(code + `\n// client ${id}`).toString('base64')}`)));
const window = new EventTarget(); globalThis.window = window;
let raw = '[]', writes = 0;
window.localStorage = { getItem: () => raw, setItem: (_key, value) => { raw = value; writes++; } };
const draft = name => ({ version: 1, id: 'draft-cross-client', name, defenders_visible: false, players: [], defenders: [], ball: null, arrows: [] });
let release, entered;
const acquired = new Promise(resolve => entered = resolve);
const holding = locks.request('arc-playbooks-v1:write', { mode: 'exclusive' }, async () => { entered(); await new Promise(resolve => release = resolve); });
await acquired;
const pending = clients.map((api, i) => api.createPlaybook(draft(`Tab ${i}`)));
for (let i = 0; i < 30; i++) await Promise.resolve();
assert.equal(writes, 0, 'no tab reads or writes a transaction while another owns the lock');
release(); await holding;
const saved = await Promise.all(pending);
assert.equal(JSON.parse(raw).length, 3, 'concurrent creates preserve every completed save');
assert.equal(new Set(saved.map(play => play.id)).size, 3);
await Promise.all([clients[0].updatePlaybook({ ...saved[0], name: 'Renamed' }), clients[1].deletePlaybook(saved[1].id), clients[2].createPlaybook(draft('New repair'))]);
assert.deepEqual(JSON.parse(raw).map(p => p.name).sort(), ['New repair', 'Renamed', 'Tab 2']);
const deleting = clients[0].deletePlaybook(saved[0].id);
const updating = clients[1].updatePlaybook({ ...saved[0], name: 'Must not recreate' });
await Promise.all([deleting, assert.rejects(updating, /not found/)]);
assert.ok(!JSON.parse(raw).some(p => p.id === saved[0].id));
const before = raw;
Object.defineProperty(navigator, 'locks', { configurable: true, value: undefined });
await assert.rejects(clients[0].createPlaybook(draft('Unsafe')), /Safe browser storage is unavailable/);
assert.equal(raw, before, 'unsupported locking never falls back to an unsafe write');
installBrowserLocks();
const originalSet = window.localStorage.setItem;
window.localStorage.setItem = () => { throw new Error('quota'); };
await assert.rejects(clients[0].createPlaybook(draft('Failed')), /could not be saved/);
window.localStorage.setItem = originalSet;
await clients[1].createPlaybook(draft('Retry'));
assert.ok(JSON.parse(raw).some(p => p.name === 'Retry'), 'failed writes release the lock');
console.log('Cross-client library transactions passed: held locks, independent clients, creates/updates/deletes, deletion preservation, unavailable locks and failed-write recovery');
