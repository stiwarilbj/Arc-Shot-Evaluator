"""Explicit offline training command — never imported by app/build/deployment"""
import json, subprocess, pathlib, hashlib
import numpy as np
import torch
root = pathlib.Path(__file__).resolve().parents[1]
torch.set_num_threads(2)
torch.manual_seed(91031)
def data(seed):
    rows = json.loads(subprocess.check_output(['node', '--experimental-strip-types', str(root / 'scripts/shotform-dataset.mjs'), str(seed)], cwd=root))
    return torch.tensor([r[0] for r in rows], dtype=torch.float32) / 8, torch.tensor([r[1] for r in rows], dtype=torch.float32) / 100
x, y = data(43117)
vx, vy = data(791915)
# ReLU network learns the three motion-feature -> stability mappings
model = torch.nn.Sequential(torch.nn.Linear(9, 32), torch.nn.ReLU(), torch.nn.Linear(32, 32), torch.nn.ReLU(), torch.nn.Linear(32, 3), torch.nn.ReLU())
optimizer = torch.optim.Adam(model.parameters(), lr=.003)
for step in range(16000):
    index = torch.randint(len(x), (512,))
    loss = ((model(x[index]) - y[index]) ** 2).mean()
    optimizer.zero_grad(); loss.backward(); optimizer.step()
    if step in (8000, 12000):
        for group in optimizer.param_groups: group['lr'] *= .3
with torch.no_grad():
    pred = model(vx).clamp(0, 1).numpy() * 100
    truth = vy.numpy() * 100
error = np.abs(pred - truth)
margin = np.sort(truth, axis=1)[:, 1] - np.sort(truth, axis=1)[:, 0]
eligible = margin > 5
report = {'samples': len(vx), 'p99': float(np.quantile(error, .99)), 'maximum': float(error.max()), 'regionAccuracy': float((pred.argmin(1)[eligible] == truth.argmin(1)[eligible]).mean()), 'eligible': int(eligible.sum()), 'trainingSeed': 91031, 'heldOutSeed': 791915}
print(json.dumps(report), flush=True)
assert report['p99'] <= 2 and report['maximum'] <= 5 and report['regionAccuracy'] >= .98, 'Model failed publication gates'
layers = [{'weights': layer.weight.detach().tolist(), 'bias': layer.bias.detach().tolist()} for layer in model if isinstance(layer, torch.nn.Linear)]
metadata = json.loads(subprocess.check_output(['node', '--experimental-strip-types', str(root / 'scripts/shotform-dataset.mjs'), '--definition'], cwd=root))
artifact = {'version': 1, **metadata, 'scale': 8, 'activation': 'relu', 'layers': layers, 'validation': report}
path = root / 'frontend/src/features/games/shotform-model.json'
path.write_text(json.dumps(artifact, separators=(',', ':')) + '\n')

(root / 'frontend/src/features/games/shotformModelIdentity.ts').write_text('// Generated by scripts/train-shotform-model.py\nexport const MOTION_MODEL_SHA256 = \"' + hashlib.sha256(path.read_bytes()).hexdigest() + '\";\n')
